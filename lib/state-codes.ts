export function placeFor(raw: string): { code: string; name: string } | null {
  if (!/^[a-zA-Z]{2}$/.test(raw)) return null
  const code = raw.toUpperCase()
  const name = NAMES[code]
  if (!name) return null
  return { code, name }
}
